export const findDepartment = (id: string) => DEPARTMENTS.find((d) => d.id === id);

export type SearchHit = {
  dept: Department;
  year: YearPlan;
  kind: "Skill" | "Tool" | "Project" | "Subject";
  text: string;
};

export function searchRoadmaps(query: string): SearchHit[] {
  const q = query.trim().toLowerCase();
  if (q.length < 2) return [];
  const hits: SearchHit[] = [];
  for (const dept of DEPARTMENTS) {
    for (const year of dept.years) {
      const push = (kind: SearchHit["kind"], list: string[]) => {
        for (const text of list) {
          if (text.toLowerCase().includes(q)) hits.push({ dept, year, kind, text });
        }
      };
      push("Subject", year.subjects);
      push("Skill", year.skills);
      push("Tool", year.tools);
      push("Project", year.projects);
    }
  }
  return hits.slice(0, 60);
}
